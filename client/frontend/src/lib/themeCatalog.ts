/** 某大类的子类清单；未知大类返回空数组。 */
export function subTypesOf(theme: string | null | undefined): SubTheme[] {
  return THEMES.find((t) => t.name === theme)?.subTypes ?? [];
}

/** 大类解读（含子类清单）。 */
export function themeEntry(theme: string | null | undefined): ThemeEntry | undefined {
  return THEMES.find((t) => t.name === theme);
}

/** 子类解读（含案例）。 */
export function subThemeEntry(
  theme: string | null | undefined,
  sub: string | null | undefined,
): SubTheme | undefined {
  return subTypesOf(theme).find((s) => s.name === sub);
}

/** 书本题材展示名：大类 · 子类（子类可空）。 */
export function themeLabel(theme?: string | null, subType?: string | null): string {
  const t = (theme || "").trim();
  const s = (subType || "").trim();
  if (t && s) return `${t} · ${s}`;
  return t || s;
}
