/**
 * 题材目录（大类 + 子类 + 每项解读与案例）——题材面板第 01 格「什么题材？」的候选源。
 *
 * 单一事实源＝后端 `genres/theme_catalog.py`；本文件必须逐字一致
 * （`client/backend/tests/test_shared_constants_parity.py` 对拍），否则作者选中的
 * 题材在后端校验不过（400「未知的题材」）。
 *
 * 存储值即**中文名**（封闭目录，名字即稳定键）；子类必须属于所选大类。
 *
 * 字段口径：
 * - `desc`    —— 这一项**写的是什么**（一句话，作者视角）
 * - `example` —— **可对照的作品/取材**（把抽象标签锚到具体印象上）
 */

export interface SubTheme {
  /** 子类名（存 story.yaml.sub_genre）。 */
  name: string;
  /** 解读：这一项写的是什么。 */
  desc: string;
  /** 案例：可对照的作品/取材。 */
  example: string;
}

export interface ThemeEntry {
  /** 大类名（存 story.yaml.genre，是书本题材展示名的主来源）。 */
  name: string;
  /** 解读：这一大类写的是什么。 */
  desc: string;
  /** 子类清单（可空选）。 */
  subTypes: SubTheme[];
}

/** 子类项工厂（后端 `_s` 同名同序，parity 正则按此格式抽取）。 */
function s(name: string, desc: string, example: string): SubTheme {
  return { name, desc, example };
}

/** 大类项工厂（后端 `_t` 同名同序）。 */
function t(name: string, desc: string, subTypes: SubTheme[]): ThemeEntry {
  return { name, desc, subTypes };
}

