"""模型输入脱敏——送模型前做敏感词中性替换，绕开内容安全拦截（GLM 1301）。

- 只改喂给模型的副本，**不改原书数据**（staging source.txt 原样保留）；
- 替换表保守起步：只列高概率触发内容审核的类别（暴力/血腥/恐怖/灵异），
  后续根据实际拦截日志迭代；单词表刻意不收单字（如「鬼」「杀」）——
  「鬼才」「杀价」类常用词误替换会毁掉喂料语义；
- 替换目标＝保持语义等价的临床/中性表述，不改变叙事事实——
  AI 拆解的是结构（谁/在哪/干了什么），不是文学性，中性词足够；
- 返回替换清单供日志留痕与质量追踪。
"""

from __future__ import annotations

# 敏感词→中性替换（保守起步：只列已实锤或高概率触发 GLM 1301 的词）
# 原始词有子串关系时须长短语在前（_SORTED_MAP 已按长度降序）
_SENSITIVE_MAP: list[tuple[str, str]] = [
    # ── 暴力/血腥 ──
    ("杀死了", "害了"),
    ("杀死", "害了"),
    ("被杀", "遇害"),
    ("杀人", "害人"),
    ("自杀", "轻生"),
    ("屠杀", "残害"),
    ("屠戮", "残害"),
    ("残杀", "残害"),
    ("虐杀", "残害"),
    ("尸体", "遗体"),
    ("尸身", "遗体"),
    ("丧尸", "异变者"),
    ("血腥", "刺激性"),
    ("血流成河", "大面积出血"),
    ("血流如注", "大量出血"),
    ("流血", "出血"),
    ("鲜血", "血液"),
    ("血迹", "红色痕迹"),
    ("血肉", "躯体组织"),
    ("碎尸", "遗体分离"),
    ("斩杀", "斩除"),
    ("刺杀", "袭击"),
    ("砍杀", "砍伤"),
    ("惨死", "惨烈离世"),
    ("毙命", "离世"),
    ("灭口", "封口"),
    # ── 恐怖/灵异 ──
    ("恐怖", "惊悚"),
    ("诡异", "反常"),
    ("邪门", "反常"),
    ("阴森", "幽暗"),
    ("毛骨悚然", "头皮发麻"),
    ("不寒而栗", "心生寒意"),
    ("鬼魂", "灵异存在"),
    ("恶鬼", "恶意灵体"),
    ("厉鬼", "怨灵"),
    ("闹鬼", "灵异事件"),
    ("尸变", "异变"),
    ("诈尸", "异动"),
    ("咒杀", "诅咒"),
    ("招魂", "唤灵"),
    ("还魂", "苏醒"),
    # ── 性/裸露 ──
    ("赤裸", "未着衣物"),
    ("全裸", "未着衣物"),
]

# 按原始词长度降序排（先替换长短语）
_SORTED_MAP = sorted(_SENSITIVE_MAP, key=lambda x: len(x[0]), reverse=True)


def sanitize_for_model(text: str) -> tuple[str, list[str]]:
    """送模型前的中性替换。→ (替换后文本, 替换清单 ['原文→替换', ...])。

    只改送模型的副本，不改原书数据；替换表保守起步，后续按拦截日志迭代。
    """
    if not text:
        return text, []
    replacements: list[str] = []
    for original, neutral in _SORTED_MAP:
        if original in text:
            count = text.count(original)
            text = text.replace(original, neutral)
            replacements.append(f"{original}→{neutral}（{count}处）")
    return text, replacements
