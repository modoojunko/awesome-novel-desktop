THEME_NAMES: tuple[str, ...] = tuple(t["name"] for t in THEMES)


def theme_entry(theme: str) -> dict | None:
    """按名取大类项（含 desc 与 sub_types）。"""
    for entry in THEMES:
        if entry["name"] == theme:
            return entry
    return None


def sub_types_of(theme: str) -> list[dict]:
    """某大类的子类清单（含 desc/example）；未知大类返回空。"""
    entry = theme_entry(theme)
    return list(entry["sub_types"]) if entry else []


def sub_type_names(theme: str) -> list[str]:
    return [s["name"] for s in sub_types_of(theme)]


def sub_type_entry(theme: str, sub: str) -> dict | None:
    for s in sub_types_of(theme):
        if s["name"] == sub:
            return s
    return None


def theme_or_none(value: str | None) -> str | None:
    """大类名校验：空值→None，不在目录→抛 ValueError（调用方转 400）。"""
    name = (value or "").strip()
    if not name:
        return None
    if name not in THEME_NAMES:
        raise ValueError(f"未知的题材：{name}")
    return name


def sub_type_or_none(theme: str | None, value: str | None) -> str | None:
    """子类名校验：须属于所选大类；无大类时子类无意义（返回 None）。"""
    sub = (value or "").strip()
    if not sub:
        return None
    if not theme:
        return None
    if sub not in sub_type_names(theme):
        raise ValueError(f"「{theme}」没有这个子类：{sub}")
    return sub
