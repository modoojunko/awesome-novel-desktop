"""概念推断——自由文本 → 六概念之一；封闭词表确定性规则，不跑模型。"""

from __future__ import annotations

_KEYWORDS: dict[str, list[str]] = {
    "文风": [
        "声音", "身份", "基调", "叙事", "视角", "冷峻", "克制", "旁白",
        "口吻", "腔调", "语感", "整体感觉",
    ],
    "文笔": [
        "句式", "节奏", "描写", "修辞", "禁用", "短句", "长句", "比喻",
        "动词", "对话", "文笔", "文字", "用词", "标点",
    ],
    "世界设定": [
        "世界", "设定", "舞台", "力量", "势力", "历史", "铁律", "规则",
        "体系", "魔法", "灵气", "境界", "功法",
    ],
    "角色设定": [
        "角色", "人物", "原型", "性格", "底子", "档案", "形象", "塑造",
        "主角", "反派", "配角", "谋士", "画像",
    ],
    "手法": [
        "手法", "技巧", "打法", "套路", "先果后因", "悬念", "伏笔", "钩子",
        "打斗", "文戏", "场面", "写法", "节奏", "反转", "视角切换",
    ],
    "情节": [
        "情节", "剧情", "套路", "结构", "节奏", "冲突", "主线", "支线", "卷",
    ],
}


def infer_concept(text: str) -> str:
    """自由文本 → 六概念之一。匹配不出返回默认"手法"。"""
    t = text.strip()
    if not t:
        return "手法"
    hits: dict[str, int] = {}
    for concept, kws in _KEYWORDS.items():
        score = sum(1 for kw in kws if kw in t)
        if score > 0:
            hits[concept] = score
    if not hits:
        return "手法"
    return max(hits, key=lambda c: (hits[c], c))
